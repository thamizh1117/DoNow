// ── SKY EFFECTS ──
function generateStars(){
  const c = document.getElementById('stars-container');
  c.innerHTML = '';
  for (let i = 0; i < 120; i++){
    const s = document.createElement('div');
    s.classList.add('star');
    const sz = Math.random() * 3 + 1;
    s.style.cssText = `width:${sz}px;height:${sz}px;top:${Math.random()*100}%;left:${Math.random()*100}%;animation-delay:${Math.random()*3}s;animation-duration:${1.5+Math.random()*2}s;`;
    c.appendChild(s);
  }
}
 
function generateClouds(){
  const c = document.getElementById('clouds-container');
  c.innerHTML = '';
  [{w:160,h:50,top:8,dur:60,delay:0},{w:220,h:65,top:18,dur:80,delay:-20},
   {w:130,h:42,top:5,dur:50,delay:-10},{w:190,h:58,top:28,dur:90,delay:-40},
   {w:110,h:36,top:35,dur:70,delay:-55}]
  .forEach(d => {
    const cl = document.createElement('div');
    cl.classList.add('cloud');
    cl.style.cssText = `width:${d.w}px;height:${d.h}px;top:${d.top}%;animation-duration:${d.dur}s;animation-delay:${d.delay}s;`;
    c.appendChild(cl);
  });
}
 
