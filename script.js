// ── STATE ──
let currentLang = localStorage.getItem('lang') || 'en';
let isDark = localStorage.getItem('theme') === 'dark';
let currentTask = "";
let historyVisible = false;
 
const XP_PER_TASK = 10;
const XP_PER_LEVEL = 1000;
const MAX_LEVEL = 1000;
 
// ── XP FUNCTIONS ──
function getXP(){ return parseInt(localStorage.getItem('xp')) || 0; }
function getLevel(xp){ return Math.min(Math.floor(xp / XP_PER_LEVEL) + 1, MAX_LEVEL); }
function getXPInLevel(xp){ return xp % XP_PER_LEVEL; }
 
function updateXPDisplay(){
  const xp = getXP();
  const level = getLevel(xp);
  const xpInLevel = getXPInLevel(xp);
  const pct = Math.round((xpInLevel / XP_PER_LEVEL) * 100);
  const label = xpInLevel + ' / ' + XP_PER_LEVEL + ' XP to next level';
  document.getElementById('level-badge').textContent = '🏆 Level ' + level;
  document.getElementById('xp').textContent = '⭐ XP: ' + xp;
  document.getElementById('xp-bar').style.width = pct + '%';
  document.getElementById('xp-bar-label').textContent = label;
  // Settings panel
  document.getElementById('settings-level-badge').textContent = 'Level ' + level;
  document.getElementById('settings-xp-text').textContent = '⭐ ' + xp + ' XP Total';
  document.getElementById('settings-xp-bar').style.width = pct + '%';
  document.getElementById('settings-xp-label').textContent = label;
}
 
function showXPToast(){
  const toast = document.getElementById('xp-toast');
  toast.textContent = '+' + XP_PER_TASK + ' XP ⭐';
  toast.classList.add('show');
  setTimeout(() => toast.classList.remove('show'), 1800);
}
 
// ── CONGRATS ──
function showCongrats(level){
  const msgs = congratsMsgs[currentLang];
  const msg = msgs[Math.floor(Math.random() * msgs.length)];
  document.getElementById('congrats-level').textContent = level;
  document.getElementById('congrats-title').textContent = txt[currentLang].levelUp;
  document.getElementById('congrats-msg').textContent = msg;
  document.querySelector('.congrats-btn').textContent = txt[currentLang].congratsBtn;
  document.getElementById('congrats-popup').classList.add('show');
}
function closeCongrats(){ document.getElementById('congrats-popup').classList.remove('show'); }
 
// ── TASKS ──
function getTasks(){ return currentLang === 'ta' ? tasks_ta : tasks_en; }
 
function getTask(){
  const tasks = getTasks();
  const random = Math.floor(Math.random() * tasks.length);
  currentTask = tasks[random];
  document.getElementById('task').textContent = currentTask;
}
 
function completeTask(){
  if (!currentTask) return;
  const oldXP = getXP();
  const oldLevel = getLevel(oldXP);
  let history = JSON.parse(localStorage.getItem('history')) || [];
  let xp = oldXP + XP_PER_TASK;
  history.push(currentTask);
  localStorage.setItem('history', JSON.stringify(history));
  localStorage.setItem('xp', xp);
  const newLevel = getLevel(xp);
  currentTask = "";
  document.getElementById('task').textContent = "";
  updateXPDisplay();
  renderHistory();
  showXPToast();
  if (newLevel > oldLevel){ setTimeout(() => showCongrats(newLevel), 600); }
}
 
// ── HISTORY ──
function toggleHistory(){
  historyVisible = !historyVisible;
  document.getElementById('history-panel').classList.toggle('show', historyVisible);
  renderHistory();
}
 
function renderHistory(){
  let history = JSON.parse(localStorage.getItem('history')) || [];
  const list = document.getElementById('history');
  const empty = document.getElementById('history-empty');
  if (history.length === 0){
    list.innerHTML = '';
    empty.style.display = 'block';
    empty.textContent = txt[currentLang].noHistory;
  } else {
    empty.style.display = 'none';
    list.innerHTML = [...history].reverse().map(t => `<li>✅ ${t}</li>`).join('');
  }
}
 
function clearHistory(){
  localStorage.removeItem('history');
  localStorage.removeItem('xp');
  currentTask = "";
  document.getElementById('task').textContent = "";
  updateXPDisplay();
  renderHistory();
}
 
